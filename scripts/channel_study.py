"""Synthetic experiment along both sides of the channel (paper protocol, Mac).

Worlds (seed 0 first): s20 = base (c 0.5, 20% false), s50 = noisy (c 0.5, 50% false), c25 = incomplete (c 0.25, 20% false).
Per world:
  A  omega in {0.5,1,1.5,2,3}: LightGCN-S, GBSR, GBSR-Detach, PU-GIB-Prune (beta 0.01)   [reuses om2_* runs]
  B  at LightGCN-S's best omega: Uniform (x GBSR mean gate at GBSR's best omega), LightGCN-PU omega_c in
     {0.05, 0.1, 0.25} for the two-hop and the global pool (K = 10), ceilings (Z, A ∩ Z, A + true ties of each pool)
  C  omega grid at the selected omega_c: LightGCN-PU (hop, global), PU-GIB beta 0.01 (hop, global candidates)
  D  if a PU-GIB variant beats GBSR and Uniform on seed 0 in a world: that world, those rows + LightGCN-S, GBSR,
     Uniform on seeds 1, 2 (seed-0 settings)
Global candidates outside Omega use rho_un estimated on Omega and RA = 0. lambda 5, sigma 0.25, kappa 0.02.

  python scripts/channel_study.py run | report
"""
import glob
import json
import os
import subprocess
import sys
import time

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, ROOT)
from src.pugib_prep import isin_pairs  # noqa: E402

WORLDS = {"s20": ("synth", 0.5, 0.2, "base: c 0.5, 20% false"), "s50": ("synth50", 0.5, 0.5, "noisy: c 0.5, 50% false"),
          "c25": ("synth_c25", 0.25, 0.2, "incomplete: c 0.25, 20% false")}
OMEGAS, OMEGA_C, POOLS = [0.5, 1, 1.5, 2, 3], [0.05, 0.1, 0.25], {"hop": "s", "glob": "global"}
H = "hsic_lambda=5 hsic_sigma=0.25"
P = "configs/paper"
GRID = {  # key -> (label, config, overrides) for methods with their own omega grid in stage A
    "lgcns": ("LightGCN-S", f"{P}/lightgcn_s.yaml --no-tune", ""),
    "gbsr": ("GBSR", f"{P}/gbsr.yaml", H),
    "gbsrdet": ("GBSR-Detach", f"{P}/gbsr_detach.yaml", H),
    "prune01": ("PU-GIB-Prune (β 0.01)", f"{P}/pugib_prune.yaml", f"kappa=0.02 beta=0.01 {H}"),
}
CGRID = {  # stage C: key -> (label, config, overrides, pool)
    "puhop": ("LightGCN-PU, two-hop pool", f"{P}/lightgcn_pu.yaml --no-tune", "pool=s", "hop"),
    "puglob": ("LightGCN-PU, global pool", f"{P}/lightgcn_pu.yaml --no-tune", "pool=global pool_k=10", "glob"),
    "pghop": ("PU-GIB, two-hop candidates (β 0.01)", f"{P}/pugib.yaml --no-tune", f"pool=s kappa=0.02 beta=0.01 {H}", "hop"),
    "pgglob": ("PU-GIB, global candidates (β 0.01)", f"{P}/pugib.yaml --no-tune", f"pool=global pool_k=10 kappa=0.02 beta=0.01 {H}", "glob"),
}
PUGIB_KEYS = ["prune01", "pghop", "pgglob"]


def fw(w):
    return str(w).replace(".", "")


def nm(world, key, w=None, suffix=""):
    return f"om2_{world}_{key}" + (f"_w{fw(w)}" if w is not None else "") + suffix


def line(world, cfg, ov, name, seed=0):
    ds = WORLDS[world][0]
    return f"- {cfg} --seeds {seed} --set dataset={ds} data_dir=data/processed/{ds} name={name} {ov}".rstrip()


def runs():
    fs = glob.glob(os.path.join(ROOT, "results/jobs/local_*.csv"))
    df = pd.concat([pd.read_csv(f) for f in fs], ignore_index=True)
    df = df[df["method"].str.startswith("om2_")].sort_values("timestamp")
    return df.groupby(["method", "seed"]).tail(1).set_index(["method", "seed"])


def val(R, n, s=0):
    return float(R.loc[(n, s), "val_ndcg@20"]) if (n, s) in R.index else np.nan


def test(R, n, s=0):
    return float(R.loc[(n, s), "test_ndcg@20"]) if (n, s) in R.index else np.nan


def best(R, world, key, grid=OMEGAS, name_fn=None):
    name_fn = name_fn or (lambda w: nm(world, key, w))
    v = {w: val(R, name_fn(w)) for w in grid}
    v = {w: x for w, x in v.items() if x == x}
    return max(v, key=v.get) if v else None


def run_list(lines, tag, par=4):
    R = runs()
    todo = [l for l in lines if (l.split("name=")[1].split()[0], int(l.split("--seeds ")[1].split()[0])) not in R.index]
    print(f"[channel] {tag}: {len(todo)} of {len(lines)} runs to do", flush=True)
    if not todo:
        return
    path = os.path.join(ROOT, f"configs/jobs/channel_{tag}.txt")
    open(path, "w").write("# generated by scripts/channel_study.py\n" + "\n".join(todo) + "\n")
    subprocess.run(["bash", os.path.join(ROOT, "scripts/run_jobs_local.sh"), path, str(par)], cwd=ROOT,
                   env=dict(os.environ, DEVICE="auto"), check=False)


def gate_mean(n, seed=0):
    z = np.load(os.path.join(ROOT, "results/pugib_runs", n, f"alpha_seed{seed}.npz"))
    return float(z["alpha"].mean()) + 0.5


def wc_name(world, pool, ws, wc):
    return nm(world, f"wc{pool}", ws, f"_c{fw(wc)}")


def best_wc(R, world, pool):
    ws = best(R, world, "lgcns")
    return best(R, world, None, OMEGA_C, lambda wc: wc_name(world, pool, ws, wc))


def stage_a():
    while any("omega_stage1" in l for l in subprocess.run(["pgrep", "-fl", "omega_stage1"], capture_output=True,
                                                             text=True).stdout.splitlines()):
        time.sleep(60)  # the earlier omega study is still computing part of this grid
    L = [line(w, cfg, f"social_omega={om} {ov}", nm(w, k, om)) for w in WORLDS for k, (_, cfg, ov) in GRID.items()
         for om in OMEGAS]
    run_list(L, "A")


def stage_b():
    R, L = runs(), []
    for w, (ds, *_) in WORLDS.items():
        ws = best(R, w, "lgcns")
        g = gate_mean(nm(w, "gbsr", best(R, w, "gbsr")))
        L.append(line(w, f"{P}/lightgcn_s.yaml --no-tune", f"social_omega={ws * g:.4f}", nm(w, "uniform")))
        for pool, pv in POOLS.items():
            for wc in OMEGA_C:
                ov = f"social_omega={ws} omega_c={wc} pool={pv}" + (" pool_k=10" if pool == "glob" else "")
                L.append(line(w, f"{P}/lightgcn_pu.yaml --no-tune", ov, wc_name(w, pool, ws, wc)))
        c = f"data/processed/{ds}/seed_0"
        for key, f in [("ceilZ", f"{c}/truth/Z.txt"), ("ceilDen", f"{c}/ceiling/a_true.txt"),
                       ("ceilHop", f"{c}/ceiling/hop_ceil_k10.txt"), ("ceilGlob", f"{c}/ceiling/glob_ceil_k10.txt")]:
            L.append(line(w, f"{P}/lightgcn_s.yaml --no-tune", f"social_omega={ws} social_edges_file={f}", nm(w, key)))
    run_list(L, "B")


def stage_c():
    R, L = runs(), []
    for w in WORLDS:
        for k, (_, cfg, ov, pool) in CGRID.items():
            wc = best_wc(R, w, pool)
            L += [line(w, cfg, f"social_omega={om} omega_c={wc} {ov}", nm(w, k, om)) for om in OMEGAS]
    run_list(L, "C")


def row_names(R, world):
    """label -> (run name, omega, omega_c) at each method's best omega."""
    out = {}
    for k, (lab, *_) in GRID.items():
        w = best(R, world, k)
        out[lab] = (nm(world, k, w), w, None)
    u = nm(world, "uniform")
    out["Uniform"] = (u, json.loads(R.loc[(u, 0), "hparams"]).get("social_omega") if (u, 0) in R.index else None, None)
    for k, (lab, _, _, pool) in CGRID.items():
        w = best(R, world, k)
        out[lab] = (nm(world, k, w), w, best_wc(R, world, pool))
    return out


def winners(R, world):
    rn = row_names(R, world)
    ref = max(test(R, rn["GBSR"][0]), test(R, rn["Uniform"][0]))
    labs = [GRID["prune01"][0], CGRID["pghop"][0], CGRID["pgglob"][0]]
    return [lab for lab in labs if test(R, rn[lab][0]) > ref]


def ensure_world(world, seed):
    ds, c, ff, _ = WORLDS[world]
    base = os.path.join(ROOT, "data/processed", ds, f"seed_{seed}")
    py = sys.executable
    if not os.path.exists(os.path.join(base, "pugib/best/priors.json")):
        subprocess.run([py, "scripts/make_synthetic.py", "--name", ds, "--c", str(c), "--false-frac", str(ff),
                        "--seed", str(seed)], cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
        subprocess.run([py, "-u", "scripts/run_experiment.py", "configs/lastfm_lightgcn.yaml", "--quiet", "--no-tune", "--seeds",
                        str(seed), "--device", "auto", "--set", f"dataset={ds}", f"data_dir=data/processed/{ds}", "reg=0.0001",
                        f"name={ds}_lightgcn_cold", f"results_csv=results/jobs/local_{ds}_cold_s{seed}.csv"],
                       cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
        subprocess.run([py, "scripts/prepare_pugib.py", "--dataset", ds, "--variants", "best", "--seeds", str(seed)],
                       cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
    if not os.path.exists(os.path.join(base, "pugib/best/global_pool_k10.txt")):
        subprocess.run([py, "scripts/make_pools.py", "--dataset", ds, "--seed", str(seed), "--K", "10"], cwd=ROOT,
                       check=True, stdout=subprocess.DEVNULL)
        subprocess.run([py, "scripts/make_global_pools.py", "--dataset", ds, "--seed", str(seed), "--K", "10"], cwd=ROOT,
                       check=True, stdout=subprocess.DEVNULL)


def stage_d():
    R, L = runs(), []
    for w in WORLDS:
        win = winners(R, w)
        print(f"[channel] {w}: PU-GIB rows beating GBSR and Uniform on seed 0: {win}", flush=True)
        if not win:
            continue
        rn = row_names(R, w)
        rows = ["LightGCN-S", "GBSR", "Uniform"] + win
        for seed in (1, 2):
            ensure_world(w, seed)
            for lab in rows:
                n, om, wc = rn[lab]
                if lab == "Uniform":
                    L.append(line(w, f"{P}/lightgcn_s.yaml --no-tune", f"social_omega={om}", n, seed))
                    continue
                spec = {v[0]: (v[1], v[2]) for v in GRID.values()} | {v[0]: (v[1], v[2]) for v in CGRID.values()}
                cfg, ov = spec[lab]
                extra = f" omega_c={wc}" if wc is not None else ""
                L.append(line(w, cfg, f"social_omega={om}{extra} {ov}", n, seed))
    if L:
        run_list(L, "D")


def auc_from_snapshot(world, n, part, seed=0):
    p = os.path.join(ROOT, "results/pugib_runs", n, f"alpha_seed{seed}.npz")
    if not os.path.exists(p):
        return np.nan
    z = np.load(p)
    ds = WORLDS[world][0]
    Z = np.loadtxt(os.path.join(ROOT, "data/processed", ds, f"seed_{seed}", "truth", "Z.txt"), dtype=np.int64)
    e, a, obs = np.sort(z["edges"].astype(np.int64), 1), z["alpha"], z["is_obs"].astype(bool)
    m = obs if part == "obs" else ~obs
    if m.sum() == 0:
        return np.nan
    y = isin_pairs(e[m], Z, int(max(e.max(), Z.max())) + 1)
    return float(roc_auc_score(y, a[m])) if 0 < y.sum() < len(y) else np.nan


def report():
    R = runs()
    out = ["# Both sides of the channel (synthetic, paper protocol, λ=5, σ=0.25, κ=0.02, K=10)", "",
           "Global candidates outside Ω receive ρ_un estimated on Ω and RA = 0. Ceilings use LightGCN-S's best ω."]
    for w, (ds, c, ff, desc) in WORLDS.items():
        rn = row_names(R, w)
        base = rn["LightGCN-S"][0]
        seeds = [s for s in (0, 1, 2) if (base, s) in R.index]
        st = json.load(open(os.path.join(ROOT, "data/processed", ds, "seed_0", "ceiling", "pool_stats.json")))
        tr = json.load(open(os.path.join(ROOT, "data/processed", ds, "seed_0", "truth", "truth.json")))["omega"]
        out += ["", f"## {desc} (`{ds}`; on Ω: c {tr['c']:.3f}, ε {tr['eps']:.4f}, κ* {tr['kappa_star']:.4f})", "",
                f"### 1-2. Test NDCG@20 at each method's best ω, paired Δ vs LightGCN-S (seeds {seeds})", "",
                "| method | ω | ω_c | " + " | ".join(f"N@20 s{s}" for s in seeds) + " | Δ mean (± std) | mask AUROC obs | mask AUROC cand |",
                "|---|---|---|" + "---|" * len(seeds) + "---|---|---|"]
        for lab, (n, om, wc) in rn.items():
            vals = [test(R, n, s) for s in seeds]
            d = np.array([test(R, n, s) - test(R, base, s) for s in seeds])
            d = d[np.isfinite(d)]
            ds_ = "–" if n == base else (f"{d.mean():+.4f} ± {d.std(ddof=1):.4f}" if len(d) > 1 else (f"{d[0]:+.4f}" if len(d) else "–"))
            mo = auc_from_snapshot(w, n, "obs") if any(t in n for t in ("gbsr", "prune", "pg")) else np.nan
            mc = auc_from_snapshot(w, n, "cand") if "_pg" in n else np.nan
            f3 = lambda x: "–" if x != x else f"{x:.3f}"
            out.append(f"| {lab} | {om} | {wc if wc is not None else '–'} | " + " | ".join("–" if x != x else f"{x:.4f}" for x in vals)
                       + f" | {ds_} | {f3(mo)} | {f3(mc)} |")
        for key, lab in [("ceilZ", "ceiling: LightGCN-S on Z"), ("ceilDen", "ceiling: A ∩ Z (denoising)"),
                         ("ceilHop", "ceiling: A + true two-hop candidates"), ("ceilGlob", "ceiling: A + true global candidates")]:
            n = nm(w, key)
            out.append(f"| {lab} | {rn['LightGCN-S'][1]} | – | {test(R, n):.4f} | " + " | ".join("" for _ in seeds[1:]) +
                       f" {test(R, n) - test(R, base):+.4f} (s0) | – | – |")
        out += ["", "### 3. Candidate pools (K = 10) and ω curves", "",
                f"Recall of missing true ties (Z \\ A_train, {st['n_missing_true']}): two-hop {st['hop_k10']['recall_missing_true']:.3f} "
                f"(precision {st['hop_k10']['precision']:.3f}, size {st['hop_k10']['size']}), global {st['glob_k10']['recall_missing_true']:.3f} "
                f"(precision {st['glob_k10']['precision']:.3f}, size {st['glob_k10']['size']}, {st['glob_k10']['frac_outside_omega']:.0%} outside Ω).", "",
                "| method | " + " | ".join(f"ω={o}" for o in OMEGAS) + " |", "|---|" + "---|" * len(OMEGAS)]
        for k, lab in [(k, v[0]) for k, v in GRID.items()] + [(k, v[0]) for k, v in CGRID.items()]:
            b = best(R, w, k)
            out.append(f"| {lab} | " + " | ".join("–" if val(R, nm(w, k, o)) != val(R, nm(w, k, o)) else
                                                   f"{val(R, nm(w, k, o)):.4f} / {test(R, nm(w, k, o)):.4f}" + (" ◀" if o == b else "")
                                                   for o in OMEGAS) + " |")
        ws = rn["LightGCN-S"][1]
        out.append("ω_c selection (LightGCN-PU at ω=" + str(ws) + ", val): " + "; ".join(
            f"{pool}: " + ", ".join(f"{wc}: {val(R, wc_name(w, pool, ws, wc)):.4f}" for wc in OMEGA_C) for pool in POOLS))
        out.append(f"PU-GIB rows beating GBSR and Uniform on seed 0: {winners(R, w)}")
    text = "\n".join(out)
    open(os.path.join(ROOT, "results/channel_study_report.md"), "w").write(text + "\n")
    print(text)


if __name__ == "__main__":
    if sys.argv[1] == "run":
        for st in (stage_a, stage_b, stage_c, stage_d):
            print(f"[channel] {st.__name__} start {time.strftime('%H:%M')}", flush=True)
            st()
    report()
