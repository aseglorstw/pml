def prep_hard():
    import shutil
    import torch
    sys.path.insert(0, os.path.join(ROOT, "scripts"))
    from hard_noise_study import canon, inject
    for w, ds in HARD_WORLDS.items():
        kind = "uniform" if w.startswith("u") else "fof"
        for s in SEEDS:
            src, dst = os.path.join(ROOT, sdir("synth_sweep_f0", s)), os.path.join(ROOT, sdir(ds, s))
            os.makedirs(os.path.join(dst, "truth"), exist_ok=True)
            os.makedirs(os.path.join(dst, "ceiling"), exist_ok=True)
            os.makedirs(os.path.join(dst, "pugib"), exist_ok=True)
            for f in ("train.txt", "val.txt", "test.txt", "social_val.txt", "meta.json", "truth/Z.txt"):
                shutil.copy(os.path.join(src, f), os.path.join(dst, f))
            meta = json.load(open(os.path.join(src, "meta.json")))
            n = meta["n_users"]
            e = canon(np.loadtxt(os.path.join(src, "social_train.txt"), dtype=np.int64))
            va = canon(np.loadtxt(os.path.join(src, "social_val.txt"), dtype=np.int64))
            Z = canon(np.loadtxt(os.path.join(src, "truth/Z.txt"), dtype=np.int64))
            inj = inject(kind, e, np.concatenate([va, Z]), n, len(e), np.random.default_rng([s, 17, 100]))
            st = np.concatenate([e, inj])
            st = st[np.lexsort((st[:, 1], st[:, 0]))]
            np.savetxt(os.path.join(dst, "social_train.txt"), st, fmt="%d")
            np.savetxt(os.path.join(dst, "truth/injected.txt"), inj, fmt="%d")
            np.savetxt(os.path.join(dst, "ceiling/a_true.txt"), e, fmt="%d")
            meta.update({"n_social_train": int(len(st)), "injected": int(len(inj)), "injected_kind": kind,
                         "base_dataset": "synth_sweep_f0"})
            json.dump(meta, open(os.path.join(dst, "meta.json"), "w"), indent=2)
            ck = os.path.join(ROOT, "results/checkpoints", f"lightgcn_synth_sweep_f0_seed{s}.pt")
            shutil.copy(ck, os.path.join(ROOT, "results/checkpoints", f"lightgcn_{ds}_seed{s}.pt"))
            run_prior(ds, s)
            run_prior(ds, s, "--reference", "matched", "--tag", "matched")
            k = len(np.loadtxt(os.path.join(dst, "pugib/map_prior.txt"), dtype=np.int64, ndmin=2))
            keep = np.sort(np.random.default_rng([s, 11]).choice(len(st), k, replace=False))
            np.savetxt(os.path.join(dst, "pugib/rand_keep.txt"), st[keep], fmt="%d")
            emb = torch.load(ck, map_location="cpu")["user_final"].numpy()
            z = emb / np.maximum(np.linalg.norm(emb, axis=1, keepdims=True), 1e-12)
            c = np.einsum("ij,ij->i", z[st[:, 0]], z[st[:, 1]])
            np.savetxt(os.path.join(dst, "pugib/share_prune.txt"), st[c > 0], fmt="%d")
            fake = isin_pairs(st, inj, n)
            msg = [f"{w} seed {s}: {len(e)} genuine + {len(inj)} {kind} false ties;"]
            for tag in ("", "_matched"):
                t = json.load(open(os.path.join(dst, f"pugib/mixture_prior{tag}.json")))["truth"]
                msg.append(f"MAP{tag}: false removed {t['map_false_removed']:.2f}, true lost {t['map_true_lost']:.2f};")
            msg.append(f"SHaRe cut: false removed {(fake & (c <= 0)).sum() / fake.sum():.2f}, true lost "
                       f"{(~fake & (c <= 0)).sum() / (~fake).sum():.2f}")
            print(" ".join(msg))


