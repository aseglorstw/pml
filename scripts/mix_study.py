SHARE_OMEGAS = [1, 1.5, 2, 3]  # weights <= 1 lower the social volume, so SHaRe gets a wider grid


def prep_share():
    import torch
    for w, (ds, _, _) in WORLDS.items():
        for s in SEEDS:
            d = os.path.join(ROOT, sdir(ds, s))
            n = json.load(open(os.path.join(d, "meta.json")))["n_users"]
            e = np.loadtxt(os.path.join(d, "social_train.txt"), dtype=np.int64)
            emb = torch.load(os.path.join(d, "pugib/best/embeddings.pt"), map_location="cpu")["user_final"].numpy()
            z = emb / np.maximum(np.linalg.norm(emb, axis=1, keepdims=True), 1e-12)
            C = z @ z.T
            c_obs = C[e[:, 0], e[:, 1]]
            cut = c_obs <= 0
            remain = e[~cut]
            M = int(cut.sum())
            iu = np.triu_indices(n, 1)
            cu = C[iu].copy()
            linked = np.zeros((n, n), bool)
            linked[e[:, 0], e[:, 1]] = linked[e[:, 1], e[:, 0]] = True
            cu[linked[iu]] = -np.inf
            top = np.argpartition(-cu, M)[:M] if M > 0 else np.zeros(0, int)
            add = np.stack([iu[0][top], iu[1][top]], 1)
            rew = np.concatenate([remain, add])
            c = C[rew[:, 0], rew[:, 1]]
            wts = (c - c.min()) / max(c.max() - c.min(), 1e-12)
            out = os.path.join(d, "pugib")
            np.savetxt(os.path.join(out, "share_prune.txt"), remain, fmt="%d")
            np.savetxt(os.path.join(out, "share_edges.txt"), rew, fmt="%d")
            np.savetxt(os.path.join(out, "share_w.txt"), wts, fmt="%.6f")
            msg = f"{w} seed {s}: cut {M} of {len(e)}, added {len(add)}, mean weight {wts.mean():.3f}"
            tz = os.path.join(d, "truth/Z.txt")
            if os.path.exists(tz):
                Z = np.loadtxt(tz, dtype=np.int64)
                true = isin_pairs(e, Z, n)
                msg += (f" | cut: false removed {(~true & cut).sum() / (~true).sum():.2f}, true lost "
                        f"{(true & cut).sum() / true.sum():.2f}; added true {isin_pairs(add, Z, n).mean():.2f}")
            print(msg)


