"""Mixture-prior study (docs/audit.md, way 1): per-tie prior from the noise share vs random pairs, MAP graph.

Worlds: noisy (synth50, c 0.5, 50% false) and base (synth, c 0.5, 20% false), seeds 0-2.
Main comparison: GBSR on the MAP graph vs GBSR on the observed graph A (same omega grid, omega picked on
seed-0 validation, paired per-user differences per seed). Controls: same number of ties removed at random;
ceiling A ∩ Z. PU-GIB-Prune with the mixture prior (beta 0.01 / 0.001); its alpha >= 0.5 gives a second
MAP graph (stage B).

  python scripts/mix_study.py prep     # local: mixture prior, MAP graph, random control, ceilings (all seeds)
  python scripts/mix_study.py jobs1    # writes configs/jobs/mix_A.txt
  python scripts/mix_study.py jobs2    # after mix_A: MAP graphs from alpha, writes configs/jobs/mix_B.txt
  python scripts/mix_study.py prep_share  # SHaRe rewiring graphs (on the cluster or locally, seconds)
  python scripts/mix_study.py jobs3    # writes configs/jobs/mix_C.txt (SHaRe baselines)
  python scripts/mix_study.py report   # table -> stdout and results/mix_study_report.md

SHaRe baseline (Jiang et al., WWW 2024, Sec. 3.1), as graph preprocessing on the same backbone: cosine c of the
interaction-only embeddings ẽ; cut every tie with c <= 0; add the M most similar unlinked pairs over all user
pairs (M = number of cut ties); weight every tie of the rewired graph by min-max normalized c (eq. 10).
Simplifications: frozen ẽ instead of an encoder recomputed every epoch; no HRA contrastive loss.
Variants: share_prune (cut only, weights 1) and share (cut + add + weights).
"""
import csv
import glob
import json
import os
import subprocess
import sys

import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, ROOT)
from src.pugib_prep import isin_pairs  # noqa: E402

# world tag -> dataset, omega of LightGCN-S, omega of PU-GIB-Prune (channel study selections)
WORLDS = {"s50": ("synth50", 2, 1.5), "s20": ("synth", 3, 2)}
SEEDS = [0, 1, 2]
GBSR_OMEGAS = [1, 1.5, 2]
BETAS = {"b01": 0.01, "b001": 0.001}
HSIC = "hsic_lambda=5 hsic_sigma=0.25"


def sdir(ds, s):
    return f"data/processed/{ds}/seed_{s}"


def prep():
    for w, (ds, _, _) in WORLDS.items():
        for s in SEEDS:
            d = os.path.join(ROOT, sdir(ds, s))
            subprocess.run([sys.executable, os.path.join(ROOT, "scripts/mixture_prior.py"), "--dataset", ds,
                            "--seeds", str(s)], check=True, stdout=subprocess.DEVNULL)
            e = np.loadtxt(os.path.join(d, "social_train.txt"), dtype=np.int64)
            k = len(np.loadtxt(os.path.join(d, "pugib/map_prior.txt"), dtype=np.int64))
            keep = np.sort(np.random.default_rng([s, 11]).choice(len(e), k, replace=False))
            np.savetxt(os.path.join(d, "pugib/rand_keep.txt"), e[keep], fmt="%d")
            ceil = os.path.join(d, "ceiling/a_true.txt")
            if not os.path.exists(ceil):
                n = json.load(open(os.path.join(d, "meta.json")))["n_users"]
                Z = np.loadtxt(os.path.join(d, "truth/Z.txt"), dtype=np.int64)
                os.makedirs(os.path.dirname(ceil), exist_ok=True)
                np.savetxt(ceil, e[isin_pairs(e, Z, n)], fmt="%d")
            info = json.load(open(os.path.join(d, "pugib/mixture_prior.json")))
            t = info["truth"]
            print(f"{w} seed {s}: q̂ Ω {info['groups'].get('in_omega', {}).get('q_hat', float('nan')):.3f} "
                  f"bridges {info['groups']['bridges']['q_hat']:.3f} | truth Ω {t['false_share_in_omega']:.3f} "
                  f"bridges {t['false_share_bridges']:.3f} | kept {info['map_kept']}/{info['n_ties']} "
                  f"false removed {t['map_false_removed']:.2f} true lost {t['map_true_lost']:.2f}")


def line(cfg, name, ds, s, extra, tune=False):
    return (f"- configs/paper/{cfg}.yaml {'' if tune else '--no-tune '}--seeds {s} --set dataset={ds} "
            f"data_dir=data/processed/{ds} name={name} {extra}").strip()


def jobs1():
    out = ["# generated by scripts/mix_study.py jobs1"]
    for w, (ds, om_l, om_p) in WORLDS.items():
        for s in SEEDS:
            d = sdir(ds, s)
            out.append(line("lightgcn_s", f"mix_{w}_lgcns_A", ds, s, f"social_omega={om_l}"))
            for tag, f in (("map", "pugib/map_prior.txt"), ("rand", "pugib/rand_keep.txt"), ("ceil", "ceiling/a_true.txt")):
                out.append(line("lightgcn_s", f"mix_{w}_lgcns_{tag}", ds, s, f"social_omega={om_l} social_edges_file={d}/{f}"))
            for om in GBSR_OMEGAS:
                wt = str(om).replace(".", "")
                out.append(line("gbsr", f"mix_{w}_gbsr_A_w{wt}", ds, s, f"social_omega={om} {HSIC}"))
                for tag, f in (("map", "pugib/map_prior.txt"), ("rand", "pugib/rand_keep.txt"), ("ceil", "ceiling/a_true.txt")):
                    out.append(line("gbsr", f"mix_{w}_gbsr_{tag}_w{wt}", ds, s,
                                    f"social_omega={om} social_edges_file={d}/{f} {HSIC}"))
            for bt, b in BETAS.items():
                out.append(line("pugib_prune", f"mix_{w}_pg_{bt}", ds, s,
                                f"prior=mixture kappa=0.02 beta={b} social_omega={om_p} {HSIC}"))
    path = os.path.join(ROOT, "configs/jobs/mix_A.txt")
    open(path, "w").write("\n".join(out) + "\n")
    print(f"wrote {path}: {len(out) - 1} jobs")


