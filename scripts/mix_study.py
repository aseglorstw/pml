# ------------------------------------------------------------------ report
def csv_rows():
    rows = {}
    for f in sorted(glob.glob(os.path.join(ROOT, "results/jobs/local_mix_*.csv"))):
        for r in csv.DictReader(open(f)):
            key = (r["method"], int(r["seed"]))
            if key not in rows or r["timestamp"] >= rows[key]["timestamp"]:
                rows[key] = r
    return rows


def peruser(ds, name, s):
    p = os.path.join(ROOT, f"results/peruser/{ds}/{name}/seed{s}.npz")
    if not os.path.exists(p):
        return None
    z = np.load(p)
    return dict(zip(z["users"].tolist(), z["ndcg"].tolist()))


def pick_omega(rows, prefix, omegas=None):
    """omega of a GBSR row family chosen on seed-0 validation NDCG@20."""
    best = None
    for om in (omegas or GBSR_OMEGAS):
        r = rows.get((f"{prefix}_w{str(om).replace('.', '')}", 0))
        if r and (best is None or float(r["val_ndcg@20"]) > best[1]):
            best = (om, float(r["val_ndcg@20"]))
    return None if best is None else f"{prefix}_w{str(best[0]).replace('.', '')}"


def mask_stats(w, ds, bt, s):
    p = os.path.join(ROOT, f"results/pugib_runs/mix_{w}_pg_{bt}/alpha_seed{s}.npz")
    if not os.path.exists(p):
        return ""
    from sklearn.metrics import roc_auc_score
    a = np.load(p)
    e, al = a["edges"][a["is_obs"]], a["alpha"][a["is_obs"]]
    d = os.path.join(ROOT, sdir(ds, s))
    n = json.load(open(os.path.join(d, "meta.json")))["n_users"]
    true = isin_pairs(np.sort(e, 1), np.loadtxt(os.path.join(d, "truth/Z.txt"), dtype=np.int64), n)
    keep = al >= 0.5
    return (f"AUROC {roc_auc_score(true, al):.3f}, α true {al[true].mean():.2f} / false {al[~true].mean():.2f}, "
            f"MAP: false removed {(~true & ~keep).sum() / (~true).sum():.2f}, true lost {(true & ~keep).sum() / true.sum():.2f}")


def report():
    rows = csv_rows()
    lines = ["# Mixture-prior study (synthetic, seeds 0-2)", "",
             "Test NDCG@20. Δ = paired per-user difference vs GBSR on A (ω picked on seed-0 validation), "
             "± SE over users; t = mean / (std over seeds / √3); one-sided 95% needs t ≥ 2.92.", ""]
    for w, (ds, _, _) in WORLDS.items():
        ref_name = pick_omega(rows, f"mix_{w}_gbsr_A")
        lines += [f"## {w} ({ds}); reference GBSR on A = {ref_name}", "",
                  "| method | N@20 s0 / s1 / s2 | Δ vs GBSR(A) s0 / s1 / s2 | mean ± std | t |", "|---|---|---|---|---|"]
        cands = [("LightGCN-S on A", f"mix_{w}_lgcns_A"), ("LightGCN-S on MAP(prior)", f"mix_{w}_lgcns_map"),
                 ("LightGCN-S, random removal", f"mix_{w}_lgcns_rand"), ("LightGCN-S on A ∩ Z (ceiling)", f"mix_{w}_lgcns_ceil")]
        for tag, lab in (("A", "GBSR on A"), ("map", "GBSR on MAP(prior)"), ("rand", "GBSR, random removal"),
                         ("ceil", "GBSR on A ∩ Z (ceiling)")):
            nm = pick_omega(rows, f"mix_{w}_gbsr_{tag}")
            if nm:
                cands.append((f"{lab} [{nm.rsplit('_', 1)[1]}]", nm))
        cands.append(("LightGCN-S, SHaRe cut only (c <= 0)", f"mix_{w}_lgcns_shp"))
        cands.append(("LightGCN-S, SHaRe rewiring + weights", f"mix_{w}_lgcns_sh"))
        for tag, lab in (("shp", "GBSR, SHaRe cut only"), ("sh", "GBSR, SHaRe rewiring + weights")):
            nm = pick_omega(rows, f"mix_{w}_gbsr_{tag}", SHARE_OMEGAS)
            if nm:
                cands.append((f"{lab} [{nm.rsplit('_', 1)[1]}]", nm))
        for bt in BETAS:
            cands.append((f"PU-GIB-Prune mixture prior, β {BETAS[bt]} (soft α)", f"mix_{w}_pg_{bt}"))
            cands.append((f"LightGCN-S on MAP(α, β {BETAS[bt]})", f"mix_{w}_lgcns_ma{bt}"))
            nm = pick_omega(rows, f"mix_{w}_gbsr_ma{bt}")
            if nm:
                cands.append((f"GBSR on MAP(α, β {BETAS[bt]}) [{nm.rsplit('_', 1)[1]}]", nm))
        for lab, nm in cands:
            vals, deltas = [], []
            for s in SEEDS:
                A, R = peruser(ds, nm, s), (peruser(ds, ref_name, s) if ref_name else None)
                if A is None:
                    vals.append("–")
                    deltas.append(None)
                    continue
                vals.append(f"{np.mean(list(A.values())):.4f}")
                if R is None:
                    deltas.append(None)
                    continue
                u = sorted(set(A) & set(R))
                dd = np.array([A[x] - R[x] for x in u])
                deltas.append((dd.mean(), dd.std(ddof=1) / np.sqrt(len(dd))))
            ds_ = [x for x in deltas if x is not None]
            ms = [x[0] for x in ds_]
            if len(ms) == 3:
                sd = np.std(ms, ddof=1)
                summ, t = f"{np.mean(ms):+.4f} ± {sd:.4f}", (f"{np.mean(ms) / (sd / np.sqrt(3)):.1f}" if sd > 0 else "–")
            else:
                summ, t = "–", "–"
            dstr = " / ".join("–" if x is None else f"{x[0]:+.4f}±{x[1]:.4f}" for x in deltas)
            lines.append(f"| {lab} | {' / '.join(vals)} | {dstr} | {summ} | {t} |")
        lines += ["", "Masks (PU-GIB-Prune, mixture prior):"]
        for bt in BETAS:
            for s in SEEDS:
                st = mask_stats(w, ds, bt, s)
                if st:
                    lines.append(f"- β {BETAS[bt]}, seed {s}: {st}")
        lines.append("")
    txt = "\n".join(lines)
    print(txt)
    open(os.path.join(ROOT, "results/mix_study_report.md"), "w").write(txt + "\n")


