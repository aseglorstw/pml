"""Why does a mask with AUROC 0.95 capture so little of the denoising ceiling? (noisy world, seed 0, Mac)

World synth50 (c 0.5, 50% false), seed 0, paper protocol, lambda 5, sigma 0.25, kappa 0.02, each method at its best
omega from the channel / omega study (LightGCN-S 2, PU-GIB-Prune 1.5 for beta 0.001 and 0.01, PU-GIB global 2,
omega_c 0.05).

  1  false observed ties inside Omega vs bridges (observed ties outside Omega) and the prior of each group
  2  alpha of the trained PU-GIB-Prune (beta 0.001, 0.01) on true / false ties, inside Omega and on bridges
  3  denoising ceiling: false ties weight 0 with the static degrees of A, vs A ∩ Z with recomputed degrees
  4  hard pruning at test time of the trained PU-GIB-Prune: alpha < t or bottom q% (chosen on validation),
     (a) static degrees, (b) degrees recomputed on the pruned graph; oracle pruning of the same model as reference
  5  PU-GIB-Prune retrained with (a) prior 0.5 on bridges, (b) no KL on bridges
  6  PU-GIB with global candidates retrained (a) without the RA feature, (b) with a 'pair in Omega' feature

  python scripts/noisy_diag.py run      # trains the 9 runs (4 in parallel), skips finished ones, then reports
  python scripts/noisy_diag.py report   # -> results/noisy_diag_report.md
"""
