"""Per-method social weight omega on synthetic data (paper protocol), two worlds:
synth (20% false observed edges) and synth50 (50%). Mac only.

Stage 1: omega in {0.5, 1, 1.5, 2, 3} for LightGCN-S, GBSR, GBSR-Detach, PU-GIB-Prune (beta 0.001 / 0.01).
Stage 2: LightGCN-PU omega_c in {0.05, 0.1, 0.25} at LightGCN-S's best omega; Uniform = LightGCN-S with every social
         entry x (LightGCN-S best omega) x (GBSR mean gate incl. +0.5 bias, at GBSR's best omega).
Stage 3: PU-GIB with candidates (beta 0.01, omega_c from LightGCN-PU) over the omega grid.
Stage 4: if PU-GIB-Prune or PU-GIB beats both GBSR and Uniform on seed 0 in a world, rerun the winning rows plus
         LightGCN-S, GBSR and Uniform (seed-0 selected settings) on seeds 1 and 2 of that world.
Selection always on validation NDCG@20 (seed 0). lambda 5, sigma 0.25, K 10, kappa 0.02 (as in the sanity suite).

  python scripts/omega_study.py run       # all stages, then the report
  python scripts/omega_study.py report    # -> results/omega_study_report.md
"""
import glob
import json
import os
import subprocess
import sys

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, ROOT)
from src.pugib_prep import isin_pairs  # noqa: E402

WORLDS = {"s20": "synth", "s50": "synth50"}
OMEGAS = [0.5, 1, 1.5, 2, 3]
OMEGA_C = [0.05, 0.1, 0.25]
H = "hsic_lambda=5 hsic_sigma=0.25"
P = "configs/paper"
METHODS = {  # key -> (label, config, extra overrides)
    "lgcns": ("LightGCN-S", f"{P}/lightgcn_s.yaml --no-tune", ""),
    "gbsr": ("GBSR", f"{P}/gbsr.yaml", H),
    "gbsrdet": ("GBSR-Detach", f"{P}/gbsr_detach.yaml", H),
    "prune001": ("PU-GIB-Prune β=0.001", f"{P}/pugib_prune.yaml", f"kappa=0.02 beta=0.001 {H}"),
    "prune01": ("PU-GIB-Prune β=0.01", f"{P}/pugib_prune.yaml", f"kappa=0.02 beta=0.01 {H}"),
    "pugib01": ("PU-GIB (candidates) β=0.01", f"{P}/pugib.yaml --no-tune", f"kappa=0.02 beta=0.01 {H}"),
}


def fmt_w(w):
    return str(w).replace(".", "")


def name(world, key, w=None, extra=""):
    return f"om2_{world}_{key}" + (f"_w{fmt_w(w)}" if w is not None else "") + extra


def line(world, cfg, overrides, nm, seed=0):
    ds = WORLDS[world]
    return f"- {cfg} --seeds {seed} --set dataset={ds} data_dir=data/processed/{ds} name={nm} {overrides}".rstrip()


def runs():
    fs = glob.glob(os.path.join(ROOT, "results/jobs/local_*.csv"))
    df = pd.concat([pd.read_csv(f) for f in fs], ignore_index=True)
    df = df[df["method"].str.startswith("om2_")].sort_values("timestamp")
    return df.groupby(["method", "seed"]).tail(1).set_index(["method", "seed"])


def val(R, nm, s=0):
    return float(R.loc[(nm, s), "val_ndcg@20"]) if (nm, s) in R.index else np.nan


def test(R, nm, s=0):
    return float(R.loc[(nm, s), "test_ndcg@20"]) if (nm, s) in R.index else np.nan


def best_w(R, world, key):
    v = {w: val(R, name(world, key, w)) for w in OMEGAS}
    v = {w: x for w, x in v.items() if x == x}
    return max(v, key=v.get) if v else None


def gate_mean(world, nm, seed=0):
    z = np.load(os.path.join(ROOT, "results/pugib_runs", nm, f"alpha_seed{seed}.npz"))
    return float(z["alpha"].mean()) + 0.5  # snapshot stores gate - bias


def run_list(lines, tag, par=4):
    path = os.path.join(ROOT, f"configs/jobs/omega_{tag}.txt")
    open(path, "w").write("# generated by scripts/omega_study.py\n" + "\n".join(lines) + "\n")
    env = dict(os.environ, DEVICE="auto")
    subprocess.run(["bash", os.path.join(ROOT, "scripts/run_jobs_local.sh"), path, str(par)], cwd=ROOT, env=env, check=False)


def stage1():
    L = []
    for world in WORLDS:
        for key in ["lgcns", "gbsr", "gbsrdet", "prune001", "prune01"]:
            _, cfg, ov = METHODS[key]
            L += [line(world, cfg, f"social_omega={w} {ov}", name(world, key, w)) for w in OMEGAS]
    run_list(L, "stage1")


def stage2():
    R, L = runs(), []
    for world in WORLDS:
        ws = best_w(R, world, "lgcns")
        L += [line(world, f"{P}/lightgcn_pu.yaml --no-tune", f"social_omega={ws} omega_c={wc}",
                   name(world, "pu", ws, f"_wc{fmt_w(wc)}")) for wc in OMEGA_C]
        g = gate_mean(world, name(world, "gbsr", best_w(R, world, "gbsr")))
        L.append(line(world, f"{P}/lightgcn_s.yaml --no-tune", f"social_omega={ws * g:.4f}", name(world, "uniform")))
    run_list(L, "stage2")


def best_wc(R, world):
    ws = best_w(R, world, "lgcns")
    v = {wc: val(R, name(world, "pu", ws, f"_wc{fmt_w(wc)}")) for wc in OMEGA_C}
    return max(v, key=v.get)


def stage3():
    R, L = runs(), []
    for world in WORLDS:
        wc = best_wc(R, world)
        _, cfg, ov = METHODS["pugib01"]
        L += [line(world, cfg, f"social_omega={w} omega_c={wc} {ov}", name(world, "pugib01", w)) for w in OMEGAS]
    run_list(L, "stage3")


def winners(R, world):
    """PU-GIB rows (key, omega) that beat both GBSR and Uniform on seed 0 (test NDCG@20 at their best omega)."""
    g = test(R, name(world, "gbsr", best_w(R, world, "gbsr")))
    u = test(R, name(world, "uniform"))
    out = []
    for key in ["prune001", "prune01", "pugib01"]:
        w = best_w(R, world, key)
        if w is not None and test(R, name(world, key, w)) > max(g, u):
            out.append((key, w))
    return out


def ensure_world(world, seed):
    ds = WORLDS[world]
    d = os.path.join(ROOT, "data/processed", ds, f"seed_{seed}", "pugib", "best", "priors.json")
    if os.path.exists(d):
        return
    ff = "0.5" if world == "s50" else "0.2"
    subprocess.run([sys.executable, "scripts/make_synthetic.py", "--name", ds, "--false-frac", ff, "--seed", str(seed)],
                   cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
    subprocess.run([sys.executable, "-u", "scripts/run_experiment.py", "configs/lastfm_lightgcn.yaml", "--quiet", "--no-tune",
                    "--seeds", str(seed), "--device", "auto", "--set", f"dataset={ds}", f"data_dir=data/processed/{ds}",
                    "reg=0.0001", f"name={ds}_lightgcn_cold", f"results_csv=results/jobs/local_{ds}_cold_s{seed}.csv"],
                   cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
    subprocess.run([sys.executable, "scripts/prepare_pugib.py", "--dataset", ds, "--variants", "best", "--seeds", str(seed)],
                   cwd=ROOT, check=True, stdout=subprocess.DEVNULL)


def stage4():
    R, L = runs(), []
    for world in WORLDS:
        win = winners(R, world)
        if not win:
            print(f"[omega] {world}: no PU-GIB row beats both GBSR and Uniform on seed 0 -> no seeds 1-2", flush=True)
            continue
        print(f"[omega] {world}: winners {win} -> seeds 1, 2", flush=True)
        ws, wg = best_w(R, world, "lgcns"), best_w(R, world, "gbsr")
        uw = json.loads(R.loc[(name(world, "uniform"), 0), "hparams"])["social_omega"]
        wc = best_wc(R, world)
        for seed in (1, 2):
            ensure_world(world, seed)
            L.append(line(world, METHODS["lgcns"][1], f"social_omega={ws}", name(world, "lgcns", ws), seed))
            L.append(line(world, METHODS["gbsr"][1], f"social_omega={wg} {H}", name(world, "gbsr", wg), seed))
            L.append(line(world, f"{P}/lightgcn_s.yaml --no-tune", f"social_omega={uw}", name(world, "uniform"), seed))
            for key, w in win:
                _, cfg, ov = METHODS[key]
                extra = f"omega_c={wc} " if key == "pugib01" else ""
                L.append(line(world, cfg, f"social_omega={w} {extra}{ov}", name(world, key, w), seed))
    if L:
        run_list(L, "stage4")


def mask_auroc(world, nm, seed=0):
    p = os.path.join(ROOT, "results/pugib_runs", nm, f"alpha_seed{seed}.npz")
    if not os.path.exists(p):
        return np.nan
    z = np.load(p)
    Z = np.loadtxt(os.path.join(ROOT, "data/processed", WORLDS[world], f"seed_{seed}", "truth", "Z.txt"), dtype=np.int64)
    e, a, obs = np.sort(z["edges"].astype(np.int64), 1), z["alpha"], z["is_obs"].astype(bool)
    y = isin_pairs(e[obs], Z, int(max(e.max(), Z.max())) + 1)
    return float(roc_auc_score(y, a[obs])) if 0 < y.sum() < len(y) else np.nan


def report():
    R = runs()
    out = ["# Per-method social weight ω (synthetic, paper protocol, λ=5, σ=0.25, K=10, κ=0.02)", ""]
    summary = {}
    for world, ds in WORLDS.items():
        out += [f"## World `{ds}` ({'20' if world == 's20' else '50'}% false observed ties)", "",
                "### 1. ω curve, seed 0 (val / test NDCG@20; ◀ = selected on val)", "",
                "| method | " + " | ".join(f"ω={w}" for w in OMEGAS) + " |", "|---|" + "---|" * len(OMEGAS)]
        for key, (lab, _, _) in METHODS.items():
            b = best_w(R, world, key)
            cells = []
            for w in OMEGAS:
                v, t = val(R, name(world, key, w)), test(R, name(world, key, w))
                cells.append("–" if v != v else f"{v:.4f} / {t:.4f}" + (" ◀" if w == b else ""))
            out.append(f"| {lab} | " + " | ".join(cells) + " |")
        ws = best_w(R, world, "lgcns")
        if ws is not None:
            pu = [(wc, val(R, name(world, "pu", ws, f"_wc{fmt_w(wc)}")), test(R, name(world, "pu", ws, f"_wc{fmt_w(wc)}")))
                  for wc in OMEGA_C]
            out += ["", f"LightGCN-PU at ω={ws} (LightGCN-S best), ω_c val / test: " +
                    ", ".join(f"ω_c={wc}: {v:.4f} / {t:.4f}" for wc, v, t in pu if v == v)]
        # paired table
        base_nm = name(world, "lgcns", ws) if ws is not None else None
        rows = [("LightGCN-S", base_nm, ws)]
        for key in ["gbsr", "gbsrdet", "prune001", "prune01", "pugib01"]:
            w = best_w(R, world, key)
            rows.append((METHODS[key][0], name(world, key, w) if w is not None else None, w))
        unif = name(world, "uniform")
        uw = json.loads(R.loc[(unif, 0), "hparams"])["social_omega"] if (unif, 0) in R.index else None
        rows.insert(3, (f"Uniform (ω = {uw})", unif, uw))
        seeds = [s for s in (0, 1, 2) if base_nm and (base_nm, s) in R.index]
        out += ["", f"### 2. Test NDCG@20 at each method's best ω, paired Δ vs LightGCN-S (seeds {seeds})", "",
                "| method | best ω | " + " | ".join(f"N@20 s{s}" for s in seeds) + " | Δ mean ± std | mask AUROC (s0) |",
                "|---|---|" + "---|" * len(seeds) + "---|---|"]
        for lab, nm, w in rows:
            if nm is None:
                continue
            vals = [test(R, nm, s) for s in seeds]
            d = np.array([test(R, nm, s) - test(R, base_nm, s) for s in seeds])
            d = d[np.isfinite(d)]
            ds_ = "–" if nm == base_nm else (f"{d.mean():+.4f} ± {d.std(ddof=1):.4f}" if len(d) > 1 else
                                             (f"{d[0]:+.4f}" if len(d) else "–"))
            auc = mask_auroc(world, nm) if any(k in nm for k in ("gbsr", "prune", "pugib")) else np.nan
            out.append(f"| {lab} | {w} | " + " | ".join("–" if x != x else f"{x:.4f}" for x in vals) +
                       f" | {ds_} | {'–' if auc != auc else f'{auc:.3f}'} |")
        bp = {k: best_w(R, world, k) for k in ["prune001", "prune01", "pugib01"]}
        out += ["", f"### 4. Best ω: LightGCN-S {ws}; " + ", ".join(f"{METHODS[k][0]} {w}" for k, w in bp.items()) +
                "; higher than LightGCN-S: " + ", ".join(f"{METHODS[k][0]}: {'yes' if (w or 0) > (ws or 0) else 'no'}"
                                                           for k, w in bp.items()), ""]
        summary[world] = {"winners_seed0": winners(R, world) if ws is not None else []}
    out += ["Stage-4 rule (rerun on seeds 1-2 if a PU-GIB row beats both GBSR and Uniform on seed 0): " + json.dumps(summary)]
    text = "\n".join(out)
    open(os.path.join(ROOT, "results/omega_study_report.md"), "w").write(text + "\n")
    print(text)


if __name__ == "__main__":
    if sys.argv[1] == "run":
        for st in (stage1, stage2, stage3, stage4):
            print(f"[omega] {st.__name__} start", flush=True)
            st()
        report()
    else:
        report()
