#!/bin/bash
# Controls, reproduction, harder noise and ablations requested in the review (one interactive GPU session).
# Run in the project folder on the cluster, after `git pull` and unpacking pugib_data_hard.tar.gz:
#   bash scripts/run_fable_steps.sh prep                  # CPU, minutes: new graphs and noisy copies
#   NPAR=4 nohup bash scripts/run_fable_steps.sh gpu > results/logs/fable_gpu.log 2>&1 &
#   nohup bash scripts/run_fable_steps.sh official > results/logs/fable_official.log 2>&1 &   # official GBSR code
#   bash scripts/run_fable_steps.sh report                # all reports
# GPU order (priority): real list: 1 GBSR without social ties (9) | 2 GBSR port on the authors' Epinions / Yelp (6)
#   | 3 friend-of-friend noise on Epinions + uniform seeds 1-2 (26) | 4 ablations on real data (24) [LGS=1: +18
#   LightGCN-S runs on real data]; then the synthetic list: ablations (18) and harder-noise worlds (48).
# Nothing existing is overwritten: new runs have new names; finished runs are skipped by the job generators.
set -euo pipefail
cd "$(dirname "$0")/.."
STAGE=${1:?prep | gpu | official | report}
if command -v module >/dev/null 2>&1; then module add "${PY_MODULE:-python/3.11.11-gcc-10.2.1-555dlyc}" >/dev/null 2>&1 || true; fi
source .venv/bin/activate
mkdir -p results/logs results/jobs configs/jobs
REAL="douban_book epinions yelp"
SEEDS="0 1 2"
# two lists: the reports find run results by list name (results/jobs/local_real_* and local_mix_*)
LIST=configs/jobs/real_fable.txt
MIX=configs/jobs/mix_fable.txt

add() {  # append a generated list $1 to list $2 (default $LIST), without finished runs (safe to resume)
  python scripts/skip_finished.py "$1" >> "${2:-$LIST}"
}

case $STAGE in
prep)
  python scripts/hard_noise_study.py --real epinions yelp --skip-synthetic --out hard_noise_real
  python scripts/posterior_diagnostics.py
  for ds in epinions yelp; do python scripts/make_gbsr_split.py --dataset $ds; done
  for ds in $REAL; do python scripts/real_study.py ablprep --dataset $ds --seeds $SEEDS; done
  python scripts/make_noisy_real.py --dataset epinions --fracs 0.5 --seeds $SEEDS --kind fof
  python scripts/make_noisy_real.py --dataset epinions --fracs 0.5 --seeds 1 2          # uniform, seed 0 exists
  python scripts/real_study.py prep --dataset epinions_fof50 --seeds $SEEDS
  python scripts/real_study.py prep --dataset epinions_n50 --seeds 1 2
  python scripts/real_study.py ablprep --dataset epinions_fof50 --seeds $SEEDS
  python scripts/real_study.py ablprep --dataset epinions_n50 --seeds $SEEDS
  ;;
gpu)
  echo "# generated by scripts/run_fable_steps.sh gpu" > "$LIST"
  echo "# generated by scripts/run_fable_steps.sh gpu" > "$MIX"
  for ds in $REAL; do python scripts/real_study.py jobs --dataset $ds --seeds $SEEDS --variants empty; add configs/jobs/real_${ds}_s012.txt; done
  add configs/jobs/gbsr_port_ey.txt
  python scripts/real_study.py jobs --dataset epinions_fof50 --seeds $SEEDS --variants A map shp sh mapm; add configs/jobs/real_epinions_fof50_s012.txt
  python scripts/real_study.py jobs --dataset epinions_n50 --seeds $SEEDS --variants A map shp sh mapm; add configs/jobs/real_epinions_n50_s012.txt
  python scripts/real_study.py jobs --dataset epinions --seeds $SEEDS --variants mapm mapp rhow add_s3t50A add_ra3t50 add_ra3t00; add configs/jobs/real_epinions_s012.txt
  for ds in douban_book yelp; do python scripts/real_study.py jobs --dataset $ds --seeds $SEEDS --variants mapm; add configs/jobs/real_${ds}_s012.txt; done
  python scripts/mix_study.py jobs_abl; add configs/jobs/mix_abl.txt "$MIX"
  python scripts/mix_study.py jobs_hard; add configs/jobs/mix_hard.txt "$MIX"
  if [ "${LGS:-0}" = 1 ]; then
    for ds in $REAL; do python scripts/real_study.py jobs --dataset $ds --seeds $SEEDS --variants lgs_A lgs_map; add configs/jobs/real_${ds}_s012.txt; done
  fi
  echo "$(date +%FT%T) $(grep -vc '^#' "$LIST") jobs in $LIST, $(grep -vc '^#' "$MIX") jobs in $MIX"
  DEVICE=${DEVICE:-cuda} bash scripts/run_jobs_local.sh "$LIST" "${NPAR:-4}"
  DEVICE=${DEVICE:-cuda} bash scripts/run_jobs_local.sh "$MIX" "${NPAR:-4}"
  echo "$(date +%FT%T) gpu stage done"
  ;;
official)  # unmodified official code; builds a dense adjacency, needs a lot of RAM (Douban needed ~20 GB)
  DATASET=epinions bash scripts/run_official_gbsr.sh "3 0.25 paper" "0 0.25 nohsic"
  DATASET=yelp bash scripts/run_official_gbsr.sh "2 0.25 paper" "0 0.25 nohsic"
  ;;
report)
  for ds in $REAL epinions_fof50 epinions_n50; do python scripts/real_study.py report --dataset $ds --seeds $SEEDS > /dev/null; done
  python scripts/mix_study.py report > /dev/null
  python scripts/summarize_gbsr_port.py > /dev/null
  echo "reports: results/real_{douban_book,epinions,yelp,epinions_fof50,epinions_n50}_report.md, results/mix_study_report.md,"
  echo "         results/gbsr_port_report.md, results/hard_noise_real.md, results/posterior_diagnostics.md"
  ;;
*) echo "unknown stage $STAGE"; exit 1 ;;
esac
